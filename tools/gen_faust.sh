#!/usr/bin/env bash
# AOT-compile every instruments/*.dsp to C++ and emit app/faust_gen/ (headers + registry).
# Each instrument gets a unique class name (unique include guards + SIG helpers) and its own namespace.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/instruments"
OUT="$ROOT/app/faust_gen"
mkdir -p "$OUT"
rm -f "$OUT"/*.hpp "$OUT"/faust_registry.h

reg_includes=""
reg_factories=""
reg_names=""

for dsp in "$SRC"/*.dsp; do
  name="$(basename "$dsp" .dsp)"
  klass="$(echo "$name" | sed -E 's/(^|_)([a-z0-9])/\U\2/g')"
  faust -lang cpp -cn "$klass" "$dsp" -o "$OUT/$name.hpp"
  reg_includes+="namespace fg_$name {
#include \"$name.hpp\"
}
#undef FAUSTCLASS
"
  reg_factories+="    if (name == \"$name\") return new fg_$name::$klass();
"
  reg_names+="    \"$name\",
"
done

cat > "$OUT/faust_registry.h" <<EOF
// GENERATED by tools/gen_faust.sh — do not edit.
#pragma once
#include <string>
#include <vector>
#include <cmath>
#include <cstdint>
#include <algorithm>
#include <faust/gui/UI.h>
#include <faust/gui/meta.h>
#include <faust/dsp/dsp.h>

$reg_includes
inline ::dsp* createFaustDsp (const std::string& name)
{
$reg_factories    return nullptr;
}

inline const std::vector<std::string>& faustDspNames()
{
    static const std::vector<std::string> names {
$reg_names    };
    return names;
}
EOF
echo "generated $(ls "$OUT" | wc -l) files in $OUT"
