#!/usr/bin/env python3
"""Regenerate docs/EVAL_SCOREBOARD.md from eval/history.jsonl + lessons.jsonl."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [json.loads(l) for l in open(f"{ROOT}/eval/history.jsonl")]
lessons = [json.loads(l) for l in open(f"{ROOT}/eval/lessons.jsonl")]
perfects = [r for r in rows if r.get("score") == 1.0]
lines = ["# EVAL SCOREBOARD (generated by tools/eval_scoreboard.py — do not hand-edit)", "",
         f"**{len(perfects)} perfect scores** across {len({r.get('genre') for r in rows})} genres evaluated; "
         f"{len(rows)} total brief runs; total spend ${sum(float(r.get('cost_usd') or 0) for r in rows):.0f}.", "",
         "## The measured-lesson ledger (pre -> post, honestly)", "",
         "| genre | pre | post | kept | lesson |", "|---|---|---|---|---|"]
for l in lessons:
    lines.append(f"| {l.get('genre')} | {l.get('pre','—')} | {l.get('post','—')} | "
                 f"{'✓' if l.get('kept') else ('✗ FALSIFIED' if l.get('kept') is False else '…')} | "
                 f"{str(l.get('lesson',''))[:110]} |")
lines += ["", "## All runs", "", "| genre | score | cost |", "|---|---|---|"]
for r in rows[-40:]:
    lines.append(f"| {r.get('genre')} | {r.get('score')} | ${float(r.get('cost_usd') or 0):.2f} |")
open(f"{ROOT}/docs/EVAL_SCOREBOARD.md", "w").write("\n".join(lines) + "\n")
print(f"scoreboard: {len(perfects)} perfects, {len(lessons)} lessons")
