#!/usr/bin/env python3
"""THE PARSE FUZZ COURT — the engine must survive ANY song.json alive.

A worldwide product means songs travel: exported, shared, hand-edited,
generated by other tools, mangled by transfers. The parse frontier
(SongLoader through m1 resave) must never DIE on garbage — a clean error
is innocence, a signal death or a hang is a conviction.

Deterministic: every case derives from (seed_song, case_index) through a
seeded RNG, so a red case replays exactly. Convicted inputs are kept in
eval/fuzz_fails/ for the autopsy.

  fuzz_court.py [--n 200] [--keep-all]     # court run (suite leg uses --n 60)

Mutation classes (the real-world garbage taxonomy):
  type-swap (num<->str<->obj<->list) · NaN/Inf injection (json allows them
  with allow_nan — real tools emit them) · sign/magnitude bombs (1e308,
  -1, 0 where positive is assumed) · missing required keys · wrong element
  types in arrays · unicode hostility (NUL escapes, RTL, emoji, 10KB names)
  · meter/tempo zeros (den 0, bpm 0) · deep-nesting bomb in extras (the
  UNDROPPABLE pass must not recurse to death) · empty/huge arrays ·
  dangling audio paths.
"""
import argparse
import copy
import json
import math
import os
import random
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
M1 = os.path.join(ROOT, "app", "build", "m1_artefacts", "Release", "m1")
SONGS = os.path.join(ROOT, "songs")
FAILS = os.path.join(ROOT, "eval", "fuzz_fails")

SEED_SONGS = ["demo_track", "untitled_36_full", "eval_funk"]

NASTY_STRINGS = ["", "\x00evil", "🎛️🎚️" * 40, "‮gnos", "x" * 10000,
                 "../../etc/passwd", "con", "nul", "-", "%s%s%n"]
NASTY_NUMBERS = [0, -1, -1e9, 1e308, -1e308, 5e-324, 2 ** 63, -(2 ** 63) - 1,
                 float("nan"), float("inf"), float("-inf"), 0.1e-40]


def all_paths(node, max_depth=12):
    """every (path, value) leaf + container, ITERATIVE with a depth cap —
    the court's own nesting bomb must not convict the court (it did:
    RecursionError on the first run, mutations after a 'deep' burst walked
    the 2000-deep bomb)."""
    out = [((), node)]
    stack = [((), node)]
    while stack:
        prefix, cur = stack.pop()
        if len(prefix) >= max_depth:
            continue
        if isinstance(cur, dict):
            items = list(cur.items())
        elif isinstance(cur, list):
            items = list(enumerate(cur))
        else:
            continue
        for k, v in items:
            out.append((prefix + (k,), v))
            stack.append((prefix + (k,), v))
    return out


def set_path(doc, path, value):
    cur = doc
    for p in path[:-1]:
        cur = cur[p]
    cur[path[-1]] = value


def del_path(doc, path):
    cur = doc
    for p in path[:-1]:
        cur = cur[p]
    del cur[path[-1]]


def mutate(doc, rng):
    """one seeded mutation burst (1..4 mutations) -> mutated doc + what-changed note"""
    doc = copy.deepcopy(doc)
    notes = []
    for _ in range(rng.randint(1, 4)):
        kind = rng.choice(["typeswap", "nan", "number", "delete", "string",
                           "meter", "tempo", "deep", "arraybomb", "elemtype"])
        paths = [p for p, v in all_paths(doc) if p]
        if not paths:
            break
        path = rng.choice(paths)
        try:
            if kind == "typeswap":
                v = rng.choice([[], {}, "surprise", 3.14, None, True])
                set_path(doc, path, v)
                notes.append(f"swap {'.'.join(map(str, path))}={type(v).__name__}")
            elif kind == "nan":
                set_path(doc, path, rng.choice([float("nan"), float("inf"), float("-inf")]))
                notes.append(f"nan {'.'.join(map(str, path))}")
            elif kind == "number":
                set_path(doc, path, rng.choice(NASTY_NUMBERS))
                notes.append(f"num {'.'.join(map(str, path))}")
            elif kind == "delete":
                del_path(doc, path)
                notes.append(f"del {'.'.join(map(str, path))}")
            elif kind == "string":
                set_path(doc, path, rng.choice(NASTY_STRINGS))
                notes.append(f"str {'.'.join(map(str, path))}")
            elif kind == "meter":
                doc["meterMap"] = [{"bar": rng.choice([0, -1, 1]),
                                    "num": rng.choice([0, -3, 7, 999]),
                                    "den": rng.choice([0, -4, 3, 8, 1024])}]
                notes.append("meter bomb")
            elif kind == "tempo":
                doc["tempoMap"] = [{"bar": rng.choice([-1, 0, 1e9]),
                                    "bpm": rng.choice([0, -120, float("nan"), 1e9]),
                                    "curve": rng.choice([float("inf"), -99])}]
                notes.append("tempo bomb")
            elif kind == "deep":
                bomb = current = {}
                for _ in range(rng.choice([50, 300, 900])):
                    current["d"] = {}
                    current = current["d"]
                if doc.get("tracks") and isinstance(doc["tracks"], list) \
                        and isinstance(doc["tracks"][0], dict):
                    doc["tracks"][0]["fuzz_extras"] = bomb
                    notes.append("deep-nest extras")
                    break                      # burst-terminator: nothing walks the bomb
            elif kind == "arraybomb":
                set_path(doc, path, [rng.choice([None, "x", {}, []])
                                     for _ in range(rng.choice([0, 1, 200]))])
                notes.append(f"array {'.'.join(map(str, path))}")
            elif kind == "elemtype":
                if doc.get("tracks") and isinstance(doc["tracks"], list) \
                        and doc["tracks"] and isinstance(doc["tracks"][0], dict):
                    doc["tracks"][0]["notes"] = [1, "two", None, {"start": "zero"}]
                    notes.append("notes elemtype")
        except Exception:
            continue
    return doc, "; ".join(notes) or "noop"


def run_case(doc, tmp_in, tmp_out, mode="resave", binary=None, timeout=45):
    """-> (verdict, detail). PASS = exited by itself with any rc; even a
    parse error is innocence. Signal death / timeout = conviction.
    mode 'render' builds the REAL engine graph (tempo math, plugins, note
    placement) — the deeper frontier resave never reaches."""
    with open(tmp_in, "w") as f:
        json.dump(doc, f, allow_nan=True)
    try:
        r = subprocess.run([binary or M1, mode, tmp_in, tmp_out],
                           capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return "HANG", f"{timeout}s timeout"
    if r.returncode < 0:
        return "SIGNAL", f"died by signal {-r.returncode}"
    if mode == "resave" and r.returncode == 0 and os.path.exists(tmp_out):
        try:
            json.load(open(tmp_out))
        except Exception as e:
            return "GARBAGE", f"resave emitted unparseable json: {e}"
        finally:
            os.remove(tmp_out)
    if os.path.exists(tmp_out):
        os.remove(tmp_out)
    return "PASS", f"rc={r.returncode}"


def selftest():
    """the court must be able to CONVICT: planted deaths through the same
    verdict plumbing (a fuzzer that can't catch anything is a fake ruler)."""
    import tempfile
    d = tempfile.mkdtemp(prefix="fuzzself_")
    ti, to = os.path.join(d, "in.json"), os.path.join(d, "out.json")
    fake_seg = os.path.join(d, "seg.sh")
    open(fake_seg, "w").write("#!/bin/bash\nkill -SEGV $$\n")
    fake_hang = os.path.join(d, "hang.sh")
    open(fake_hang, "w").write("#!/bin/bash\nsleep 600\n")
    os.chmod(fake_seg, 0o755)
    os.chmod(fake_hang, 0o755)
    v1, _ = run_case({}, ti, to, binary=fake_seg)
    v2, _ = run_case({}, ti, to, binary=fake_hang, timeout=2)
    v3, _ = run_case(json.load(open(os.path.join(SONGS, SEED_SONGS[0] + ".json"))), ti, to)
    ok = v1 == "SIGNAL" and v2 == "HANG" and v3 == "PASS"
    print(f"fuzz court selftest: SIGNAL={v1} HANG={v2} clean={v3} -> "
          + ("PROVEN" if ok else "BROKEN"))
    return 0 if ok else 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--render", action="store_true",
                    help="fuzz the RENDER frontier (engine graph; slower, deeper)")
    ap.add_argument("--selftest", action="store_true")
    args = ap.parse_args()
    if args.selftest:
        return selftest()
    if selftest() != 0:      # the ruler proves itself before every verdict
        return 1
    rng = random.Random(args.seed)
    seeds = []
    for s in SEED_SONGS:
        p = os.path.join(SONGS, s + ".json")
        if os.path.exists(p):
            seeds.append((s, json.load(open(p))))
    if not seeds:
        print("fuzz court: no seed songs found")
        return 1
    import tempfile
    tdir = tempfile.mkdtemp(prefix="fuzzcourt_")   # render output stays OFF the repo
    tmp_in = os.path.join(tdir, "_fuzz_case.json")
    tmp_out = os.path.join(tdir, "_fuzz_out." + ("wav" if args.render else "json"))
    mode = "render" if args.render else "resave"
    convictions = []
    for i in range(args.n):
        name, base = seeds[i % len(seeds)]
        doc, what = mutate(base, rng)
        verdict, detail = run_case(doc, tmp_in, tmp_out, mode=mode)
        if verdict != "PASS":
            os.makedirs(FAILS, exist_ok=True)
            keep = os.path.join(FAILS, f"case_{args.seed}_{i}_{verdict}.json")
            with open(keep, "w") as f:
                json.dump(doc, f, allow_nan=True, indent=1)
            convictions.append((i, name, verdict, detail, what, keep))
            print(f"  XX case {i} [{name}] {verdict}: {detail}  ({what[:90]})")
    for f in (tmp_in, tmp_out):
        if os.path.exists(f):
            os.remove(f)
    print(f"fuzz court: {args.n - len(convictions)}/{args.n} survived "
          f"({len(convictions)} convictions)"
          + (f" — cases kept in {FAILS}" if convictions else ""))
    return 1 if convictions else 0


if __name__ == "__main__":
    sys.exit(main())
