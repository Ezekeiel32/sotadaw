#!/usr/bin/env python3
"""THE FACTORY ADVISOR (W6 final piece): telemetry + eval history -> proposed graph patches.

Reads Genre.accept_rate (from kg_ingest_telemetry) and eval/history.jsonl, finds weak spots,
and writes eval/factory_proposals.md — PROPOSALS ONLY, a human (or a supervised agent run)
applies them via kg.py. The meta-loop's steering wheel, never an autopilot.
"""
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
from kg import KG

kg = KG()
lines = ["# Factory proposals — auto-generated by tools/factory_advisor.py", ""]

# 1) genres whose eval scores lag
hist = {}
hp = os.path.join(ROOT, "eval", "history.jsonl")
if os.path.exists(hp):
    for ln in open(hp):
        try:
            r = json.loads(ln)
        except json.JSONDecodeError:
            continue
        if "score" in r and r.get("genre"):
            hist.setdefault(r["genre"], []).append(r)

for g, runs in sorted(hist.items()):
    last = runs[-1]
    if last["score"] >= 0.8:
        continue
    fails = [k for k, v in last.get("checks", {}).items() if not v]
    lines.append(f"## {g}: score {last['score']:.2f} (latest run)")
    lines.append(f"- failing checks: {', '.join(fails) or 'none recorded'}")
    props = []
    for f in fails:
        if "clip" in f or "lufs" in f or "peak" in f:
            props.append(f"  - PROPOSE: strengthen `{g}_mix` MixTarget provenance with this failure; "
                         f"add Technique edge to gain_staged_saturation / loudness_recovery")
        elif "swing" in f or "groove" in f:
            props.append(f"  - PROPOSE: link Genre '{g}' to a Groove (library/grooves.json) and "
                         f"recompile the skill with an explicit groove law")
        else:
            props.append(f"  - PROPOSE: add a lesson Technique for '{f}' with provenance eval:{g}")
    lines.extend(dict.fromkeys(props))          # dedupe, order-preserving
    lines.append(f"- then: `tools/skill_compiler.py {g} --publish` + rerun `eval_daw.py --brief {g}`")
    lines.append("")

# 2) genres with poor accept rates in live telemetry
res = kg.g.query("MATCH (g:Genre) WHERE g.accept_rate IS NOT NULL RETURN g.name, g.accept_rate")
for row in res.result_set:
    name, rate = row[0], float(row[1])
    if rate < 0.5:
        lines.append(f"## {name}: live accept_rate {rate:.0%}")
        lines.append(f"- users reject most proposals here. PROPOSE: inspect telemetry/proposals.jsonl "
                     f"prompts for '{name}', distill the gap into a Technique, recompile.")
        lines.append("")

# 3) genres in the graph with no eval coverage at all
covered = set(hist)
res = kg.g.query("MATCH (g:Genre) RETURN g.name")
uncovered = [r[0] for r in res.result_set if r[0] not in covered and r[0] != "_untagged"]
if uncovered:
    lines.append(f"## eval coverage gap: {len(uncovered)} genres never brief-tested")
    lines.append(f"- {', '.join(sorted(uncovered)[:30])}")
    lines.append("- PROPOSE: run the suite when budget is approved (`suite_runner.py --budget <N>` — hard stop-loss, resume-safe, dry-run first)")
    lines.append("")

out = os.path.join(ROOT, "eval", "factory_proposals.md")
open(out, "w").write("\n".join(lines))
print(f"{out}: {sum(1 for l in lines if l.startswith('## '))} proposal groups")
