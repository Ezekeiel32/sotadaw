#!/usr/bin/env python3
"""THE TASTE DASHBOARD (BEST_DAW_30 #4c) — the taste circle, on one page.

The circle exists (deck WHY -> prompt quote -> telemetry -> graph -> compiled
skill) but its state was invisible: accept rates and complaint buckets lived as
Genre properties nobody surfaced, and eval scores lived in a separate ledger.
One read-only report joins them:

  genre | verdicts | accept% | top complaints | last eval score | last WHYs

Writes eval/TASTE_DASHBOARD.md (sorted worst-accept-rate first — the fix list)
and prints the top of it. Zero writes to the graph; safe under any parallel
session. Run: .venv/bin/python tools/taste_dashboard.py [--min-verdicts N]
"""
import argparse, json, os, sys, time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from kg import KG

HISTORY = os.path.join(ROOT, "eval", "history.jsonl")
OUT = os.path.join(ROOT, "eval", "TASTE_DASHBOARD.md")


def latest_eval_scores():
    """genre -> (score, when) from the newest brief rows in eval history."""
    scores = {}
    if not os.path.exists(HISTORY):
        return scores
    for line in open(HISTORY):
        try:
            row = json.loads(line)
        except Exception:
            continue
        g = row.get("genre")
        sc = row.get("score")
        if g and sc is not None:
            scores[g] = sc                     # file is chronological: last wins
    return scores


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--min-verdicts", type=int, default=1,
                    help="hide genres with fewer verdicts than this")
    a = ap.parse_args()
    kg = KG()
    rows = kg.q("MATCH (g:Genre) WHERE g.verdicts_n IS NOT NULL "
                "RETURN g.name, g.verdicts_n, g.accept_rate, g.complaints, g.last_whys")
    scores = latest_eval_scores()
    table = []
    for name, n, rate, comp, whys in rows:
        if name == "_untagged" or (n or 0) < a.min_verdicts:
            continue
        table.append({"genre": name, "n": int(n or 0),
                      "rate": float(rate) if rate is not None else None,
                      "complaints": comp or "", "whys": whys or "",
                      "eval": scores.get(name)})
    # worst accept-rate first = the fix list; unrated genres sink to the bottom
    table.sort(key=lambda r: (r["rate"] if r["rate"] is not None else 2.0, -r["n"]))
    untag = kg.q("MATCH (g:Genre {name:'_untagged'}) RETURN g.verdicts_n, g.accept_rate")
    lines = ["# TASTE DASHBOARD (generated by tools/taste_dashboard.py — do not hand-edit)",
             "", f"*{time.strftime('%Y-%m-%d %H:%M')} · {len(table)} genres with verdicts"
             + (f" · _untagged: {untag[0][0]} rows @ {untag[0][1]}*" if untag else "*"), "",
             "| genre | verdicts | accept | complaints | last eval | last WHYs |",
             "|---|---|---|---|---|---|"]
    for r in table:
        lines.append("| {genre} | {n} | {rate} | {complaints} | {eval} | {whys} |".format(
            genre=r["genre"], n=r["n"],
            rate=(f"{r['rate']:.0%}" if r["rate"] is not None else "—"),
            complaints=r["complaints"] or "—",
            eval=(r["eval"] if r["eval"] is not None else "—"),
            whys=(r["whys"][:90] or "—").replace("|", "/")))
    if not table:
        lines.append("| (no attributed verdicts yet) | | | | | |")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:14]))
    if len(table) > 8:
        print(f"... {len(table) - 8} more rows in {os.path.relpath(OUT, ROOT)}")
    print(f"taste dashboard -> {os.path.relpath(OUT, ROOT)} ({len(table)} genres)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
